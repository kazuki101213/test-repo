const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const { File } = require('node:buffer');
const source = ts.transpileModule(fs.readFileSync('apps/admin/src/photoSave.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {}, File, navigator: {}, URL, document: {}, window: {}, fetch: async url => new Response(url, { headers: { 'Content-Type': 'image/jpeg' } }) };
vm.runInNewContext(source, context);
(async () => {
  const controller = new AbortController();
  const files = await context.exports.preparePhotoFiles([{ url: 'a' }, { url: 'b' }, { url: 'c' }], 2204, controller.signal);
  assert.equal(files.length, 3);
  assert.equal(files[2].name, '2204_photo_3.jpg');
  let shared;
  context.navigator = { canShare: ({ files }) => files.length === 3, share: data => { shared = data.files; return Promise.resolve(); } };
  const result = context.exports.savePhotoFiles(files, '写真');
  assert.equal(shared, files, 'Sharing must start synchronously during the click');
  assert.equal(await result, 'share');
  context.navigator.share = () => Promise.reject(new DOMException('cancelled', 'AbortError'));
  await assert.rejects(context.exports.savePhotoFiles(files, '写真'), { name: 'AbortError' });
  context.fetch = async () => new Response('failed', { status: 500 });
  await assert.rejects(context.exports.preparePhotoFiles([{ url: 'bad' }], 2204, controller.signal));
  await assert.rejects(context.exports.savePhotoFiles([], '写真'));
  const downloaded = [];
  context.navigator = {};
  context.document = { body: { appendChild() {} }, createElement: () => ({ click() { downloaded.push(this.download); }, remove() {} }) };
  context.window = { setTimeout: fn => fn() };
  assert.equal(await context.exports.savePhotoFiles(files, '写真'), 'download');
  assert.deepEqual(downloaded, Array.from(files, file => file.name));
  console.log('All photos, synchronous mobile sharing, cancellation, failed fetch and download fallback passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
